"""Extract NASA wall triangles as a geometry source for future remeshing.

Preserve the original half-surface and patch IDs. A separate mirrored STL welds
the symmetry-plane vertices, records that operation, and requires manifold edges.
No volume mesh is generated by this script.
"""
from pathlib import Path
import argparse,json,struct
import numpy as np

def export(source,destination):
    source,destination=Path(source),Path(destination);destination.mkdir(parents=True,exist_ok=True)
    xyz=np.fromfile(source/'points.bin',dtype='<f8').reshape(-1,3)
    boundary=np.fromfile(source/'boundary.bin',dtype='<i4').reshape(-1,5);wall=boundary[boundary[:,3]==1]
    used,indices=np.unique(wall[:,:3],return_inverse=True);points=xyz[used].copy();tri=indices.reshape(-1,3)
    np.savez_compressed(destination/'CRM_half_surface.npz',points=points,triangles=tri,patch=wall[:,4],original_vertex_id=used)
    def edge_counts(faces):
        edges=np.sort(np.vstack((faces[:,[0,1]],faces[:,[1,2]],faces[:,[2,0]])),axis=1)
        return np.unique(edges,axis=0,return_counts=True)
    edges,counts=edge_counts(tri);open_edges=edges[counts==1]
    if np.any(counts>2):raise ValueError('nonmanifold half-surface')
    tolerance=1e-7
    if not np.all(np.abs(points[open_edges,1])<=tolerance):raise ValueError('surface has openings outside the symmetry plane')
    on_plane=np.abs(points[:,1])<=tolerance;max_shift=float(np.abs(points[on_plane,1]).max());points[on_plane,1]=0
    mirror=points.copy();mirror[:,1]*=-1
    ids=np.empty(len(points),dtype=np.int32);ids[on_plane]=np.flatnonzero(on_plane)
    ids[~on_plane]=len(points)+np.arange(np.count_nonzero(~on_plane))
    full_points=np.vstack((points,mirror[~on_plane]));full_tri=np.vstack((tri,ids[tri[:,::-1]]))
    full_edges,full_counts=edge_counts(full_tri)
    if not np.all(full_counts==2):raise ValueError('mirrored surface is not closed and manifold')
    vertices=full_points[full_tri];normals=np.cross(vertices[:,1]-vertices[:,0],vertices[:,2]-vertices[:,0]);area2=np.linalg.norm(normals,axis=1)
    if np.any(area2<=0):raise ValueError('degenerate surface triangle')
    normals/=area2[:,None]
    # Orient the closed shell by signed volume while preserving source patches.
    signed_volume=float(np.sum(np.einsum('ij,ij->i',vertices[:,0],np.cross(vertices[:,1],vertices[:,2])))/6)
    if signed_volume<0:vertices=vertices[:,::-1];normals=-normals;signed_volume=-signed_volume
    records=np.zeros(len(vertices),dtype=np.dtype([('normal','<f4',(3,)),('vertices','<f4',(3,3)),('attribute','<u2')]))
    records['normal']=normals;records['vertices']=vertices
    with (destination/'CRM_full_closed.stl').open('wb') as stream:
        stream.write(b'NASA DPW4 CRM: mirrored wall triangles; coordinates normalized by MAC'.ljust(80,b' '));stream.write(struct.pack('<I',len(records)));records.tofile(stream)
    np.savez_compressed(destination/'CRM_full_closed.npz',points=full_points,triangles=full_tri,patch=np.tile(wall[:,4],2))
    info=dict(source='NASA DPW4 dpw-wbt0_med-10Mc_5',half_triangles=len(tri),full_triangles=len(full_tri),
        half_open_edges=len(open_edges),full_open_edges=int(np.count_nonzero(full_counts!=2)),patch_count=len(np.unique(wall[:,4])),
        coordinates='x/c,y/c,z/c with c=275.8 original inches',source_half_surface_preserved=True,
        symmetry_weld_tolerance=tolerance,max_symmetry_vertex_shift=max_shift,closed_surface_volume=signed_volume,
        next_step='Independent volume remeshing; STL is a tessellated surface rather than exact CAD.')
    (destination/'surface_manifest.json').write_text(json.dumps(info,indent=2)+'\n');print(json.dumps(info,indent=2))

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',required=True);p.add_argument('--out',required=True)
    a=p.parse_args();export(a.source,a.out)
